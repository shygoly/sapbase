import { readFileSync } from 'fs'
import { resolve } from 'path'
import { randomUUID } from 'crypto'
import { DataSource } from 'typeorm'

interface MysqlRow {
  [key: string]: string | number | null
}

interface BuildMasterOptions {
  organizationId?: string
  organizationIdByTenantId?: Record<string, string>
}

export interface MasterDatasets {
  ships: Array<Record<string, unknown>>
  charters: Array<Record<string, unknown>>
  voyages: Array<Record<string, unknown>>
  voyageFuels: Array<Record<string, unknown>>
}

export function buildMasterDatasets(sql: string, options: BuildMasterOptions): MasterDatasets {
  const shipRows = parseTableRows(sql, 'ship_info')
  const charterRows = parseTableRows(sql, 'ship_charter_info')
  const voyageRows = parseTableRows(sql, 'ship_voyage')
  const shipTypeRows = parseTableRows(sql, 'ship_type')
  const fuelTypeRows = parseTableRows(sql, 'fuel_type')
  const shipTypeMap = new Map(shipTypeRows.map((row) => [String(row.id), String(row.ship_type_code)]))
  const fuelTypeMap = new Map(fuelTypeRows.map((row) => [String(row.id), String(row.fuel)]))

  const ships = shipRows.map((row) => ({
    sourceId: toNumber(row.id),
    organizationId: resolveOrganizationId(row.tenant_id, options),
    name: String(row.ship_name),
    imo: String(row.imo_number),
    type: shipTypeMap.get(String(row.ship_type_id)) ?? String(row.ship_type_id),
    shipTypeId: toNumber(row.ship_type_id),
    gt: toNumber(row.gross_tonnage),
    dwt: toNumber(row.dead_weight),
    status: toShipStatus(row.status),
    ciiMeasureStandard: nullableString(row.cii_measure_standard),
    ciiApplicable: toBoolean(row.cii_applicable),
    windAssistedPropulsion: nullableString(row.wind_assisted_propulsion),
    flagState: nullableString(row.flag_state),
    mainEnginePower: nullableNumber(row.main_engine_power),
    auxiliaryEnginePower: nullableNumber(row.auxiliary_engine_power),
    isWindPowerApplicable: nullableBoolean(row.is_wind_power_applicable),
    windEquipmentInstallationTime: nullableString(row.wind_equipment_installation_time),
    constantA: nullableNumber(row.constant_a),
    constantCapacity: nullableNumber(row.constant_capacity),
    constantC: nullableNumber(row.constant_c),
  }))

  const charters = charterRows.map((row) => ({
    sourceId: toNumber(row.id),
    shipSourceId: toNumber(row.ship_id),
    organizationId: resolveOrganizationId(row.tenant_id, options),
    contractNo: nullableString(row.contract_no),
    charterer: String(row.charterer_name ?? ''),
    startDate: toDateString(row.lease_start_date),
    endDate: toDateString(row.lease_end_date),
    status: 'ACTIVE',
    allocation: nullableString(row.lease_type),
    contractPath: nullableString(row.contract_path),
    mainFuelType: resolveFuelCode(row.main_fuel_type, fuelTypeMap),
    auxiliaryFuelType: resolveFuelCode(row.auxiliary_fuel_type, fuelTypeMap),
    mainFuelConsumption: nullableNumber(row.main_fuel_consumption),
    auxiliaryFuelConsumption: nullableNumber(row.auxiliary_fuel_consumption),
    shoreElectricityKwh: nullableNumber(row.shore_electricity),
    bdnPath: nullableString(row.bdn_path),
    isAutoGenerated: nullableBoolean(row.is_auto_generated),
  }))

  const voyages = voyageRows.map((row) => ({
    sourceId: toNumber(row.id),
    shipSourceId: toNumber(row.ship_id),
    charterSourceId: row.charter_info_id === null ? null : toNumber(row.charter_info_id),
    organizationId: resolveOrganizationId(row.tenant_id, options),
    voyageNo: `VOY-${toNumber(row.id)}`,
    departurePort: String(row.start_port),
    departurePortCode: nullableString(row.start_port_code),
    arrivalPort: String(row.end_port),
    arrivalPortCode: nullableString(row.end_port_code),
    departureDate: toDateString(row.departure_time),
    arrivalDate: toDateString(row.arrival_time),
    departureTime: nullableString(row.departure_time),
    arrivalTime: nullableString(row.arrival_time),
    arrivalPurpose: nullableString(row.arrival_purpose),
    distanceNm: nullableNumber(row.route_distance) ?? 0,
    emissions: 0,
    totalEuEts: nullableNumber(row.total_eu_ets),
    shorePowerConsumptionMj: row.shore_power_consumption === null ? null : roundTo(toNumber(row.shore_power_consumption) * 3.6, 3),
    bdnPath: nullableString(row.bdn_path),
    chartererName: nullableString(row.charterer_name),
    throughIce: normalizeThroughIce(row.through_ice),
    status: 'COMPLETED',
  }))

  const voyageFuels = voyageRows.flatMap((row) => {
    const fuels: Array<Record<string, unknown>> = []
    if (row.fuel_type && row.fuel_consumption !== null) {
      fuels.push({
        voyageSourceId: toNumber(row.id),
        fuelCode: resolveFuelCode(row.fuel_type, fuelTypeMap) ?? String(row.fuel_type),
        consumption: toNumber(row.fuel_consumption),
        isMain: true,
      })
    }
    if (row.auxiliary_fuel_type && row.auxiliary_fuel_consumption !== null) {
      fuels.push({
        voyageSourceId: toNumber(row.id),
        fuelCode: resolveFuelCode(row.auxiliary_fuel_type, fuelTypeMap) ?? String(row.auxiliary_fuel_type),
        consumption: toNumber(row.auxiliary_fuel_consumption),
        isMain: false,
      })
    }
    return fuels
  })

  return { ships, charters, voyages, voyageFuels }
}

export async function importMasterDatasets(
  dataSource: DataSource,
  datasets: MasterDatasets,
): Promise<void> {
  const shipIdMap = new Map<number, string>()
  const charterIdMap = new Map<number, string>()
  const voyageIdMap = new Map<number, string>()

  await dataSource.query('DELETE FROM "shipping_voyage_fuels"')
  await dataSource.query('DELETE FROM "shipping_voyages"')
  await dataSource.query('DELETE FROM "shipping_charters"')
  await dataSource.query('DELETE FROM "shipping_ships"')

  const ships = datasets.ships.map((ship) => {
    const id = randomUUID()
    shipIdMap.set(ship.sourceId as number, id)
    return { id, ...stripSourceFields(ship, ['sourceId']) }
  })
  await insertRows(dataSource, 'shipping_ships', ships)

  const charters = datasets.charters.map((charter) => {
    const id = randomUUID()
    charterIdMap.set(charter.sourceId as number, id)
    return {
      id,
      ...stripSourceFields(charter, ['sourceId', 'shipSourceId']),
      shipId: shipIdMap.get(charter.shipSourceId as number),
    }
  })
  await insertRows(dataSource, 'shipping_charters', charters)

  const voyages = datasets.voyages.map((voyage) => {
    const id = randomUUID()
    voyageIdMap.set(voyage.sourceId as number, id)
    return {
      id,
      ...stripSourceFields(voyage, ['sourceId', 'shipSourceId', 'charterSourceId']),
      shipId: shipIdMap.get(voyage.shipSourceId as number),
      charterId:
        voyage.charterSourceId === null || voyage.charterSourceId === undefined
          ? null
          : charterIdMap.get(voyage.charterSourceId as number) ?? null,
    }
  })
  await insertRows(dataSource, 'shipping_voyages', voyages)

  const voyageFuels = datasets.voyageFuels.map((fuel) => ({
    id: randomUUID(),
    ...stripSourceFields(fuel, ['voyageSourceId']),
    voyageId: voyageIdMap.get(fuel.voyageSourceId as number),
  }))
  await insertRows(dataSource, 'shipping_voyage_fuels', voyageFuels)
}

export async function importMasterFromMysqlDump(sqlPath: string, organizationId?: string): Promise<MasterDatasets> {
  const sql = readFileSync(sqlPath, 'utf8')
  const dataSource = new DataSource({
    type: 'postgres',
    host: process.env.DB_HOST || 'localhost',
    port: parseInt(process.env.DB_PORT || '5432'),
    username: process.env.DB_USERNAME || 'mac',
    password: process.env.DB_PASSWORD || '',
    database: process.env.DB_NAME || 'carbon',
    entities: [],
    synchronize: false,
    logging: false,
  })

  await dataSource.initialize()
  try {
    const organizationIdByTenantId = await ensureOrganizationsForTenantIds(
      dataSource,
      extractMasterTenantIds(sql),
      organizationId,
    )
    const datasets = buildMasterDatasets(sql, { organizationId, organizationIdByTenantId })
    await importMasterDatasets(dataSource, datasets)
    return datasets
  } finally {
    await dataSource.destroy()
  }
}

async function insertRows(dataSource: DataSource, tableName: string, rows: Array<Record<string, unknown>>): Promise<void> {
  if (rows.length === 0) {
    return
  }

  const chunkSize = 500
  for (let index = 0; index < rows.length; index += chunkSize) {
    const chunk = rows.slice(index, index + chunkSize)
    const columns = Object.keys(chunk[0])
    const values: unknown[] = []
    const groups = chunk.map((row, rowIndex) => {
      const placeholders = columns.map((column, columnIndex) => {
        values.push(row[column] ?? null)
        return `$${rowIndex * columns.length + columnIndex + 1}`
      })
      return `(${placeholders.join(', ')})`
    })

    await dataSource.query(
      `INSERT INTO "${tableName}" (${columns.map((column) => `"${column}"`).join(', ')}) VALUES ${groups.join(', ')}`,
      values,
    )
  }
}

function stripSourceFields<T extends Record<string, unknown>>(row: T, fields: string[]): Record<string, unknown> {
  return Object.fromEntries(Object.entries(row).filter(([key]) => !fields.includes(key)))
}

function parseTableRows(sql: string, tableName: string): MysqlRow[] {
  const columns = parseCreateColumns(sql, tableName)
  if (columns.length === 0) {
    return []
  }

  const insertRegex = new RegExp('INSERT INTO \\x60' + escapeRegExp(tableName) + '\\x60 VALUES \\((.*)\\);', 'g')
  const rows: MysqlRow[] = []
  let match: RegExpExecArray | null

  while ((match = insertRegex.exec(sql)) !== null) {
    const values = splitSqlValues(match[1])
    rows.push(Object.fromEntries(columns.map((column, index) => [column, parseSqlValue(values[index] ?? 'NULL')])))
  }

  return rows
}

function parseCreateColumns(sql: string, tableName: string): string[] {
  const createRegex = new RegExp('CREATE TABLE \\x60' + escapeRegExp(tableName) + '\\x60\\s*\\(([\\s\\S]*?)\\)\\s*ENGINE', 'm')
  const createMatch = sql.match(createRegex)
  if (!createMatch) {
    return []
  }

  return createMatch[1]
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.startsWith('`'))
    .map((line) => line.match(/^`([^`]+)`/)?.[1])
    .filter((column): column is string => Boolean(column))
}

function splitSqlValues(input: string): string[] {
  const values: string[] = []
  let current = ''
  let inString = false
  let escaped = false

  for (let index = 0; index < input.length; index += 1) {
    const char = input[index]

    if (escaped) {
      current += char
      escaped = false
      continue
    }

    if (char === '\\') {
      current += char
      escaped = true
      continue
    }

    if (char === "'") {
      current += char
      inString = !inString
      continue
    }

    if (char === ',' && !inString) {
      values.push(current.trim())
      current = ''
      continue
    }

    current += char
  }

  if (current.length > 0) {
    values.push(current.trim())
  }

  return values
}

function parseSqlValue(rawValue: string): string | number | null {
  const normalized = rawValue.trim()
  if (normalized === 'NULL') {
    return null
  }
  if (normalized.startsWith("'") && normalized.endsWith("'")) {
    return normalized.slice(1, -1).replace(/\\'/g, "'")
  }
  const numeric = Number(normalized)
  return Number.isNaN(numeric) ? normalized : numeric
}

function toNumber(value: string | number | null): number {
  if (typeof value === 'number') return value
  if (value === null || value === '') return 0
  return Number(value)
}

function nullableNumber(value: string | number | null): number | null {
  if (value === null || value === '') return null
  return toNumber(value)
}

function nullableString(value: string | number | null): string | null {
  if (value === null || value === '') return null
  return String(value)
}

function nullableBoolean(value: string | number | null): boolean | null {
  if (value === null || value === '') return null
  return toBoolean(value)
}

function resolveFuelCode(
  value: string | number | null,
  fuelTypeMap: Map<string, string>,
): string | null {
  if (value === null || value === '') {
    return null
  }
  return fuelTypeMap.get(String(value)) ?? String(value)
}

function resolveOrganizationId(
  tenantIdValue: string | number | null,
  options: BuildMasterOptions,
): string | null {
  const tenantId = String(tenantIdValue ?? '').trim()
  if (!tenantId) {
    return options.organizationId ?? null
  }

  return options.organizationIdByTenantId?.[tenantId] ?? options.organizationId ?? null
}

function extractMasterTenantIds(sql: string): string[] {
  const tableNames = ['ship_info', 'ship_charter_info', 'ship_voyage']
  return [
    ...new Set(
      tableNames.flatMap((tableName) =>
        parseTableRows(sql, tableName)
          .map((row) => String(row.tenant_id ?? '').trim())
          .filter(Boolean),
      ),
    ),
  ]
}

async function ensureOrganizationsForTenantIds(
  dataSource: DataSource,
  tenantIds: string[],
  defaultOrganizationId?: string,
): Promise<Record<string, string>> {
  const organizationIdByTenantId: Record<string, string> = {}
  const sortedTenantIds = [...new Set(tenantIds)].sort((left, right) => Number(left) - Number(right))

  for (const tenantId of sortedTenantIds) {
    if (tenantId === '1' && defaultOrganizationId) {
      organizationIdByTenantId[tenantId] = defaultOrganizationId
      continue
    }

    const slug = `legacy-tenant-${tenantId}`
    const existing = await dataSource.query('SELECT id FROM organizations WHERE slug = $1 LIMIT 1', [slug])
    if (existing[0]?.id) {
      organizationIdByTenantId[tenantId] = existing[0].id as string
      continue
    }

    const inserted = await dataSource.query(
      'INSERT INTO organizations (id, name, slug, "subscriptionStatus", "createdAt", "updatedAt") VALUES (gen_random_uuid(), $1, $2, $3, NOW(), NOW()) RETURNING id',
      [`Legacy Tenant ${tenantId}`, slug, 'active'],
    )
    organizationIdByTenantId[tenantId] = inserted[0].id as string
  }

  return organizationIdByTenantId
}

function toBoolean(value: string | number | null): boolean {
  if (typeof value === 'number') return value === 1
  return ['1', 'true', 'yes', 'YES', 'Y'].includes(String(value))
}

function toDateString(value: string | number | null): string | null {
  if (value === null || value === '') return null
  return String(value).slice(0, 10)
}

function toShipStatus(value: string | number | null): string {
  return toNumber(value) === 1 ? 'ACTIVE' : 'INACTIVE'
}

function normalizeThroughIce(value: string | number | null): boolean {
  return ['1', 'true', 'yes', 'y', 'YES'].includes(String(value ?? '').trim())
}

function roundTo(value: number, digits: number): number {
  const factor = 10 ** digits
  return Math.round(value * factor) / factor
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

async function main(): Promise<void> {
  const sqlPath = process.argv[2] ?? resolve(process.cwd(), '../tests/route_carbon_analyzer_backup.sql')
  const organizationId = process.argv[3] ?? process.env.DEFAULT_ORGANIZATION_ID ?? '00000000-0000-0000-0000-000000000001'
  const datasets = await importMasterFromMysqlDump(sqlPath, organizationId)
  process.stdout.write(
    `Imported master datasets: ships=${datasets.ships.length}, charters=${datasets.charters.length}, voyages=${datasets.voyages.length}, fuels=${datasets.voyageFuels.length}\n`,
  )
}

if (require.main === module) {
  main().catch((error) => {
    console.error('Master import error:', error)
    process.exit(1)
  })
}
