export function parseMysqlDumpMetadata(
  sql: string,
  tableNames: string[],
): Record<string, MysqlTableMetadata> {
  return Object.fromEntries(
    tableNames.map((tableName) => {
      const createRegex = new RegExp(
        `CREATE TABLE \\\`${escapeRegExp(tableName)}\\\`\\s*\\(([\\s\\S]*?)\\)\\s*ENGINE`,
        'm',
      )
      const createMatch = sql.match(createRegex)
      const columnLines = createMatch?.[1]
        ? createMatch[1]
            .split('\n')
            .map((line) => line.trim())
            .filter((line) => line.startsWith('`'))
        : []
      const columns = columnLines
        .map((line) => line.match(/^`([^`]+)`/))
        .map((match) => match?.[1])
        .filter((column): column is string => Boolean(column))

      const insertRegex = new RegExp(`INSERT INTO \\\`${escapeRegExp(tableName)}\\\``, 'g')
      const insertCount = (sql.match(insertRegex) ?? []).length

      return [
        tableName,
        {
          tableName,
          columns,
          insertCount,
        },
      ]
    }),
  )
}

export function compareSchemaMappings(
  mysqlMetadata: Record<string, MysqlTableMetadata>,
  pgColumns: PgColumnRow[],
  mappings: TableMapping[] = DEFAULT_TABLE_MAPPINGS,
): SchemaGapReportItem[] {
  const pgColumnsByTable = groupPgColumns(pgColumns)

  return mappings.map((mapping) => {
    const mysqlTableMetadata = mysqlMetadata[mapping.mysqlTable] ?? {
      tableName: mapping.mysqlTable,
      columns: [],
      insertCount: 0,
    }
    const combinedPgColumns = Array.from(
      new Set(
        mapping.pgTables.flatMap((pgTable) => pgColumnsByTable[pgTable] ?? []),
      ),
    )

    const mappedFields = Object.entries(mapping.fieldMap)
      .filter(([mysqlColumn, pgColumn]) => {
        return mysqlTableMetadata.columns.includes(mysqlColumn) && combinedPgColumns.includes(pgColumn)
      })
      .map(([mysqlColumn, pgColumn]) => `${mysqlColumn}→${pgColumn}`)

    const missingPgFields = mysqlTableMetadata.columns.filter((mysqlColumn) => {
      const mappedColumn = mapping.fieldMap[mysqlColumn]
      if (mappedColumn) {
        return !combinedPgColumns.includes(mappedColumn)
      }

      return !combinedPgColumns.includes(mysqlColumn)
    })

    const mysqlCoveredColumns = new Set([
      ...mysqlTableMetadata.columns,
      ...Object.values(mapping.fieldMap),
    ])
    const extraPgFields = combinedPgColumns.filter((column) => !mysqlCoveredColumns.has(column))

    const blockingGaps = (mapping.blockingFields ?? []).filter((column) => missingPgFields.includes(column))

    return {
      mysqlTable: mapping.mysqlTable,
      pgTable: mapping.pgTables.join(' + '),
      insertCount: mysqlTableMetadata.insertCount,
      mysqlColumns: mysqlTableMetadata.columns,
      pgColumns: combinedPgColumns,
      mappedFields,
      missingPgFields,
      extraPgFields,
      status: deriveStatus(mapping, mysqlTableMetadata.columns, combinedPgColumns),
      blockingGaps,
    }
  })
}

export function renderMarkdownReport(items: SchemaGapReportItem[]): string {
  const lines = [
    '# Shipping MySQL Dump vs PostgreSQL Gap Report',
    '',
    '| MySQL Table | PostgreSQL Table | Status | Source Rows | Missing Fields | Blocking Gaps |',
    '| --- | --- | --- | ---: | --- | --- |',
    ...items.map((item) => {
      const missingFields = item.missingPgFields.join(', ') || '-'
      const blockingGaps = item.blockingGaps.join(', ') || '-'
      return `| ${item.mysqlTable} | ${item.pgTable || '-'} | ${item.status} | ${item.insertCount} | ${missingFields} | ${blockingGaps} |`
    }),
    '',
  ]

  for (const item of items) {
    lines.push(`## ${item.mysqlTable}`)
    lines.push('')
    lines.push(`- PostgreSQL: ${item.pgTable || 'N/A'}`)
    lines.push(`- Status: ${item.status}`)
    lines.push(`- Source Rows: ${item.insertCount}`)
    lines.push(`- Mapped Fields: ${item.mappedFields.join(', ') || '-'}`)
    lines.push(`- Missing Fields: ${item.missingPgFields.join(', ') || '-'}`)
    lines.push(`- Extra PG Fields: ${item.extraPgFields.join(', ') || '-'}`)
    lines.push(`- Blocking Gaps: ${item.blockingGaps.join(', ') || '-'}`)
    lines.push('')
  }

  return `${lines.join('\n').trim()}\n`
}

function groupPgColumns(pgColumns: PgColumnRow[]): Record<string, string[]> {
  return pgColumns.reduce<Record<string, string[]>>((accumulator, row) => {
    accumulator[row.tableName] ??= []
    accumulator[row.tableName].push(row.columnName)
    return accumulator
  }, {})
}

function deriveStatus(
  mapping: TableMapping,
  mysqlColumns: string[],
  pgColumns: string[],
): SchemaGapReportItem['status'] {
  if (mapping.status === 'recompute') {
    return 'recompute'
  }

  if (mapping.pgTables.length === 0 || pgColumns.length === 0) {
    return 'missing'
  }

  const missingCount = mysqlColumns.filter((column) => {
    const mappedColumn = mapping.fieldMap[column] ?? column
    return !pgColumns.includes(mappedColumn)
  }).length

  if (missingCount === 0) {
    return mapping.pgTables.length > 1 ? 'split' : 'direct'
  }

  return mapping.status
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function queryPgColumns(): PgColumnRow[] {
  const output = execFileSync(
    'psql',
    [
      '-h',
      process.env.DB_HOST ?? 'localhost',
      '-U',
      process.env.DB_USERNAME ?? 'mac',
      '-d',
      process.env.DB_NAME ?? 'carbon',
      '-At',
      '-F',
      '\t',
      '-c',
      "SELECT table_name, column_name, data_type, is_nullable FROM information_schema.columns WHERE table_schema='public' AND table_name LIKE 'shipping_%' ORDER BY table_name, ordinal_position;",
    ],
    {
      env: {
        ...process.env,
        PGPASSWORD: process.env.DB_PASSWORD ?? '',
      },
      encoding: 'utf8',
    },
  )

  return output
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const [tableName, columnName, dataType, isNullable] = line.split('\t')
      return { tableName, columnName, dataType, isNullable }
    })
}

export function generateComparisonReport(sql: string, pgColumns: PgColumnRow[]): string {
  const mysqlMetadata = parseMysqlDumpMetadata(
    sql,
    DEFAULT_TABLE_MAPPINGS.map((mapping) => mapping.mysqlTable),
  )
  const comparison = compareSchemaMappings(mysqlMetadata, pgColumns)
  return renderMarkdownReport(comparison)
}

export function main(): void {
  const sqlPath = process.argv[2] ?? resolve(process.cwd(), '../../tests/route_carbon_analyzer_backup.sql')
  const outputPath = process.argv[3] ?? resolve(process.cwd(), '../../docs/reports/shipping-mysql-pg-gap-report.md')
  const sql = readFileSync(sqlPath, 'utf8')
  const pgColumns = queryPgColumns()
  const markdown = generateComparisonReport(sql, pgColumns)

  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, markdown, 'utf8')
  process.stdout.write(`Report written to ${outputPath}\n`)
}

if (require.main === module) {
  main()
}
