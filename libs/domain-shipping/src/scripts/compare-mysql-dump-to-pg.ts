export interface MysqlTableMetadata {
  tableName: string
  columns: string[]
  insertCount: number
}

export interface PgColumnRow {
  tableName: string
  columnName: string
  dataType: string
  isNullable: string
}

export interface SchemaGapReportItem {
  mysqlTable: string
  pgTable: string
  insertCount: number
  mysqlColumns: string[]
  pgColumns: string[]
  mappedFields: string[]
  missingPgFields: string[]
  extraPgFields: string[]
  status: 'direct' | 'partial' | 'split' | 'recompute' | 'missing'
  blockingGaps: string[]
}

interface TableMapping {
  mysqlTable: string
  pgTables: string[]
  status: SchemaGapReportItem['status']
  fieldMap: Record<string, string>
  blockingFields?: string[]
}

